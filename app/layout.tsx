// app/layout.tsx
import { Suspense } from 'react'
import { GlobalUIProvider } from '@/components/common/Layout/GlobalUI'
import MainLayout from '@/components/common/Layout/MainLayout'
import MainScript from '@/components/common/MainScript'
import StoreProvider from '@/components/common/Layout/StoreProvider'
import { repositoryName } from '@/prismicio'
import { PrismicPreview } from '@prismicio/next'
import type { Metadata } from 'next'
import { Literata, Tangerine } from 'next/font/google'
import { primaryFont } from './font'
import 'swiper/css'
import 'swiper/css/grid'
import 'swiper/css/navigation'
import 'swiper/css/pagination'
import './globals.css'
import { cookies } from 'next/headers'
import { cookie } from '@prismicio/client'

const tangerineFont = Tangerine({
  variable: '--font-tangerine-sans',
  subsets: ['latin'],
  weight: ['400', '700'],
})

const literataFont = Literata({
  variable: '--font-literata-sans',
  subsets: ['latin'],
  weight: ['200', '700'],
})

export const metadata: Metadata = {
  title: 'Printwork',
  description: 'Generated by create next app',
}


async function RootLayoutContent({ children }: { children: React.ReactNode }) {
  const cookiePreview = (await cookies()).get(cookie.preview)?.value
  return (
    <html
      lang="en"
      className={`${tangerineFont.variable} ${literataFont.variable} ${primaryFont.variable} antialiased`}
    >
      <body>
        <StoreProvider>
          <GlobalUIProvider>
            <MainLayout cookie={cookiePreview}>{children}</MainLayout>
            <PrismicPreview repositoryName={repositoryName} />
          </GlobalUIProvider>
        </StoreProvider>
        <MainScript />
      </body>
    </html>
  )
}

export default function RootLayout({
  children,
}: {
  children: React.ReactNode
}) {
  return (
    <Suspense>
      <RootLayoutContent>{children}</RootLayoutContent>
    </Suspense>
  )
}
